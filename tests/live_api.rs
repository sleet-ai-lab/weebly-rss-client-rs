//! Integration test against the live Weebly API.
//!
//! The test is skipped unless `WEBLY_LIVE_TESTS=1` is set, because it talks
//! to weebly.com and would otherwise make the test suite depend on the
//! network.
//!
//! ```text
//! WEBLY_LIVE_TESTS=1 cargo test --test live_api -- --nocapture
//! ```

use std::time::Duration;

use weebly_rss_client_rs::{WeeblyClient, WeeblyError};

/// Returns `true` when the live tests are enabled.
fn live_tests_enabled() -> bool {
    std::env::var("WEBLY_LIVE_TESTS").is_ok_and(|value| value == "1")
}

/// Builds a client with the timeout used by the live tests.
fn client() -> WeeblyClient {
    WeeblyClient::new().with_timeout(Duration::from_secs(30))
}

/// A known-good blog: the feed must load and carry posts.
#[tokio::test]
async fn fetches_a_known_blogs_feed() {
    if !live_tests_enabled() {
        eprintln!("skipping: set WEBLY_LIVE_TESTS=1 to run the live tests");
        return;
    }

    let feed = client()
        .fetch_feed("maerenfroespeaker", Some("blog"))
        .await
        .expect("the feed of maerenfroespeaker must load");

    assert!(
        feed.items.len() > 10,
        "expected more than 10 items, got {}",
        feed.items.len()
    );

    assert_eq!(
        feed.generator.as_deref(),
        Some("Weebly"),
        "the channel must be generated by Weebly"
    );

    assert_eq!(
        feed.site_subdomain(),
        Some("maerenfroespeaker"),
        "the channel link must yield the site's subdomain"
    );

    let with_body = feed
        .items
        .iter()
        .filter(|post| post.content_text.is_some())
        .count();

    assert!(
        with_body > 0,
        "expected at least one post with a body, got {with_body}"
    );

    println!(
        "maerenfroespeaker: {} posts, {with_body} with body, site {:?}, blog {:?}",
        feed.items.len(),
        feed.site_name(),
        feed.blog_name()
    );
}

/// The numbered feed path of the same site must serve the same posts.
#[tokio::test]
async fn fetches_a_blogs_feed_from_a_numbered_path() {
    if !live_tests_enabled() {
        eprintln!("skipping: set WEBLY_LIVE_TESTS=1 to run the live tests");
        return;
    }

    let feed = client()
        .fetch_feed("thesunshining", Some("2"))
        .await
        .expect("the feed of thesunshining must load");

    assert!(
        !feed.items.is_empty(),
        "the numbered feed path must carry posts"
    );

    println!(
        "thesunshining/2: {} posts, blog {:?}",
        feed.items.len(),
        feed.blog_name()
    );
}

/// An unknown site must be reported as `is_site_not_found`.
#[tokio::test]
async fn reports_a_missing_site() {
    if !live_tests_enabled() {
        eprintln!("skipping: set WEBLY_LIVE_TESTS=1 to run the live tests");
        return;
    }

    let error = client()
        .fetch_feed("zzz-not-a-real-weebly-site-9x8y7z", None)
        .await
        .expect_err("an unknown site must not produce a feed");

    assert!(
        error.is_site_not_found(),
        "expected a site-not-found error, got: {error}"
    );

    assert!(
        matches!(error, WeeblyError::SiteNotFound(_)),
        "expected the SiteNotFound variant, got: {error}"
    );

    println!("missing site reported as: {error}");
}
